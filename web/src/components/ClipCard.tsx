import { useId, useState } from 'react'
import { errorMessage, getClipText, type Clip } from '../api'
import { formatClipRange, formatDuration, formatSpeakers, formatTimestamp, matchedByText, talkLabelText } from '../format'
import { Spinner } from './Spinner'

type TextState = { status: 'idle' } | { status: 'loading' } | { status: 'error'; message: string } | { status: 'ready'; text: string }

const LABEL_STYLE: Record<string, string> = {
  deep_dive: 'border-emerald-700 bg-emerald-50 text-emerald-950',
  intro: 'border-sky-700 bg-sky-50 text-sky-950',
  pitch: 'border-amber-700 bg-amber-50 text-amber-950',
}

export function ClipCard({ clip, index, toolNames }: { clip: Clip; index: number; toolNames: Map<string, string> }) {
  const titleId = useId()
  const captionsId = useId()
  const [open, setOpen] = useState(false)
  const [text, setText] = useState<TextState>({ status: 'idle' })

  const start = formatTimestamp(clip.start_sec)
  const end = formatTimestamp(clip.end_sec)
  const label = talkLabelText(clip.talk_label)
  const found = matchedByText(clip.matched_by)
  const tools = clip.matched_tools.map((id) => toolNames.get(id) ?? id)

  async function loadText() {
    setText({ status: 'loading' })
    try {
      const result = await getClipText(clip.clip_id)
      setText({ status: 'ready', text: result.text })
    } catch (error) {
      setText({ status: 'error', message: errorMessage(error) })
    }
  }

  function toggleRead() {
    const next = !open
    setOpen(next)
    if (next && (text.status === 'idle' || text.status === 'error')) void loadText()
  }

  return (
    <article
      aria-labelledby={titleId}
      className="rounded-xl border border-slate-300 bg-white p-4 shadow-sm sm:p-5"
    >
      <div className="flex flex-wrap items-center gap-2 text-xs font-medium">
        <span className="text-slate-700">Clip {index + 1}</span>
        {label ? (
          <span className={`rounded-full border px-2 py-0.5 ${LABEL_STYLE[clip.talk_label ?? ''] ?? ''}`}>{label}</span>
        ) : null}
        {found ? (
          <span className="rounded-full border border-slate-300 bg-slate-50 px-2 py-0.5 text-slate-800">{found}</span>
        ) : null}
      </div>

      <h3 id={titleId} className="mt-2 text-lg font-semibold leading-snug text-slate-900">
        {clip.title}
      </h3>
      <p className="mt-1 text-sm text-slate-700">
        {formatSpeakers(clip.speakers)}
        <span aria-hidden="true"> · </span>
        <span className="sr-only">. Clip runs </span>
        <span className="font-mono tabular-nums text-slate-900">{formatClipRange(clip.start_sec, clip.end_sec)}</span>
        <span className="text-slate-700"> ({formatDuration(clip.end_sec - clip.start_sec)})</span>
      </p>

      {clip.why ? (
        <p className="mt-3 text-slate-900">
          <span className="font-semibold">Why for you: </span>
          {clip.why}
        </p>
      ) : null}
      {tools.length > 0 ? (
        <p className="mt-1 text-sm text-slate-700">
          Matched: <span className="font-medium text-slate-900">{tools.join(', ')}</span>
        </p>
      ) : null}

      {clip.quote ? (
        <blockquote className="mt-3 border-l-4 border-slate-300 pl-3 text-slate-800 italic">“{clip.quote}”</blockquote>
      ) : null}

      <div className="mt-4 flex flex-wrap gap-2">
        <a
          href={clip.watch_url}
          target="_blank"
          rel="noopener noreferrer"
          className="inline-flex items-center gap-1.5 rounded-lg bg-indigo-700 px-4 py-2 text-sm font-semibold text-white hover:bg-indigo-800"
        >
          Watch
          <span className="sr-only">
            {' '}
            {clip.title} from {start} to {end} (opens YouTube in a new tab)
          </span>
          <span aria-hidden="true">↗</span>
        </a>
        <button
          type="button"
          aria-expanded={open}
          aria-controls={captionsId}
          onClick={toggleRead}
          className="inline-flex items-center gap-1.5 rounded-lg border border-slate-400 bg-white px-4 py-2 text-sm font-semibold text-slate-900 hover:bg-slate-100"
        >
          <span aria-hidden="true">{open ? '▾' : '▸'}</span>
          Read
          <span className="sr-only"> automatic captions for {clip.title}</span>
        </button>
      </div>

      <div id={captionsId} hidden={!open} className="mt-3">
        <section aria-label={`Automatic captions: ${clip.title}`} className="rounded-lg bg-slate-50 p-3 text-sm">
          <h4 className="font-semibold text-slate-900">Automatic captions</h4>
          <p className="text-xs text-slate-700">Machine-generated by YouTube; names and terms may be misheard.</p>
          <div aria-live="polite" aria-busy={text.status === 'loading'} className="mt-2">
            {text.status === 'loading' ? (
              <p className="flex items-center gap-2 text-slate-700">
                <Spinner /> Loading captions…
              </p>
            ) : null}
            {text.status === 'error' ? (
              <p className="text-red-800">
                Could not load the captions: {text.message}{' '}
                <button type="button" onClick={() => void loadText()} className="font-semibold underline">
                  Try again
                </button>
              </p>
            ) : null}
            {text.status === 'ready' ? <p className="whitespace-pre-line leading-relaxed text-slate-900">{text.text}</p> : null}
          </div>
        </section>
      </div>
    </article>
  )
}
